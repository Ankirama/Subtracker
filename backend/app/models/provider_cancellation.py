"""
SQLAlchemy model for provider cancellation information.
Stores cancellation instructions, difficulty ratings, and AI research results.
"""
from sqlalchemy import Column, String, Boolean, DateTime, Text, Float, Enum as SQLEnum
from sqlalchemy.dialects.postgresql import UUID, JSONB
from sqlalchemy.sql import func
import uuid
import enum

from app.database import Base


class DifficultyRating(str, enum.Enum):
    """Enum for cancellation difficulty levels"""
    EASY = "easy"          # 1-2 clicks, straightforward
    MEDIUM = "medium"      # 3-5 steps, moderate complexity
    HARD = "hard"          # Phone/chat required, complex process


class InstructionsSource(str, enum.Enum):
    """Enum for instruction source tracking"""
    MANUAL = "manual"              # Manually entered by admin
    AI_GENERATED = "ai_generated"  # Generated by AI research
    COMMUNITY = "community"        # Contributed by users
    VERIFIED = "verified"          # Verified by admin/testing


class ProviderCancellationInfo(Base):
    """
    Provider cancellation information model.

    Stores cancellation instructions, links, and metadata for subscription providers.
    Supports both manual entry and AI-generated research results.
    """
    __tablename__ = "provider_cancellation_info"

    # Primary key
    id = Column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4, index=True)

    # Provider identification
    provider_name = Column(String(255), nullable=False, unique=True, index=True)

    # Cancellation information
    cancellation_url = Column(Text, nullable=True)  # Direct link to cancellation page
    difficulty_rating = Column(
        SQLEnum(DifficultyRating, name="difficulty_rating_enum", values_callable=lambda x: [e.value for e in x]),
        nullable=False,
        default=DifficultyRating.MEDIUM.value,
        index=True
    )

    # Instructions stored as JSON array of steps
    # Format: ["Step 1: ...", "Step 2: ...", ...]
    instructions = Column(JSONB, nullable=True)

    # Source tracking
    instructions_source = Column(
        SQLEnum(InstructionsSource, name="instructions_source_enum", values_callable=lambda x: [e.value for e in x]),
        nullable=False,
        default=InstructionsSource.AI_GENERATED.value,
        index=True
    )

    # Cancellation method requirements
    requires_phone_call = Column(Boolean, default=False, nullable=False)
    requires_chat = Column(Boolean, default=False, nullable=False)

    # Pause option support
    allows_pause = Column(Boolean, default=False, nullable=False)
    pause_instructions = Column(JSONB, nullable=True)  # JSON array like instructions

    # Verification tracking
    last_verified_at = Column(DateTime(timezone=True), nullable=True)
    verification_notes = Column(Text, nullable=True)

    # AI research metadata (for AI-generated instructions)
    ai_research_prompt = Column(Text, nullable=True)      # What we asked the AI
    ai_research_response = Column(Text, nullable=True)    # Full AI response
    ai_confidence_score = Column(Float, nullable=True)    # 0.0 to 1.0

    # Additional metadata
    additional_notes = Column(Text, nullable=True)        # Important warnings, timing notes, etc.
    estimated_time_minutes = Column(Float, nullable=True) # Estimated time to cancel

    # Common pitfalls or gotchas (JSON array)
    # Format: ["Watch out for...", "Make sure to...", ...]
    cancellation_gotchas = Column(JSONB, nullable=True)

    # Timestamps
    created_at = Column(DateTime(timezone=True), server_default=func.now(), nullable=False)
    updated_at = Column(DateTime(timezone=True), server_default=func.now(), onupdate=func.now(), nullable=False)

    def __repr__(self):
        return f"<ProviderCancellationInfo(provider={self.provider_name}, difficulty={self.difficulty_rating})>"

    @property
    def is_verified(self) -> bool:
        """Check if cancellation info has been verified"""
        return self.last_verified_at is not None

    @property
    def needs_reverification(self) -> bool:
        """Check if cancellation info needs reverification (>90 days old)"""
        if not self.last_verified_at:
            return True

        from datetime import datetime, timedelta
        age_days = (datetime.now(self.last_verified_at.tzinfo) - self.last_verified_at).days
        return age_days > 90

    @property
    def is_ai_generated(self) -> bool:
        """Check if instructions were AI-generated"""
        return self.instructions_source == InstructionsSource.AI_GENERATED
