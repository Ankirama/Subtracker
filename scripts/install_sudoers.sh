#!/bin/bash
#
# Install sudoers configuration for deploy user
# Allows deploy user to run backup scripts without password
#
# Usage: sudo ./install_sudoers.sh [deploy_user]
#

set -e

# Colors
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
NC='\033[0m'

# Check root
if [ "$EUID" -ne 0 ]; then
    echo -e "${RED}This script must be run as root (sudo)${NC}"
    exit 1
fi

# Configuration
DEPLOY_USER="${1:-deploy}"
PROJECT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SUDOERS_FILE="/etc/sudoers.d/subscription-tracker-backup"

echo -e "${GREEN}=== Installing Sudoers Configuration ===${NC}"
echo "Deploy user: $DEPLOY_USER"
echo "Project dir: $PROJECT_DIR"
echo ""

# Verify user exists
if ! id "$DEPLOY_USER" &>/dev/null; then
    echo -e "${RED}Error: User '$DEPLOY_USER' does not exist${NC}"
    exit 1
fi

# Create sudoers file
cat > "$SUDOERS_FILE" << EOF
# Sudoers configuration for Subscription Tracker backup
# Generated by: scripts/install_sudoers.sh
# Deploy user: $DEPLOY_USER
# Project dir: $PROJECT_DIR

# Allow deploy user to run backup setup script
$DEPLOY_USER ALL=(root) NOPASSWD: $PROJECT_DIR/scripts/setup_cron_backup.sh
$DEPLOY_USER ALL=(root) NOPASSWD: $PROJECT_DIR/scripts/setup_cron_backup.sh --status
$DEPLOY_USER ALL=(root) NOPASSWD: $PROJECT_DIR/scripts/setup_cron_backup.sh --uninstall

# Allow deploy user to run manual backup
$DEPLOY_USER ALL=(root) NOPASSWD: $PROJECT_DIR/scripts/backup_postgres.sh
EOF

# Set correct permissions (required for sudoers.d files)
chmod 440 "$SUDOERS_FILE"

# Validate sudoers syntax
if visudo -c -f "$SUDOERS_FILE" &>/dev/null; then
    echo -e "${GREEN}✓ Sudoers file installed: $SUDOERS_FILE${NC}"
else
    echo -e "${RED}Error: Invalid sudoers syntax - removing file${NC}"
    rm -f "$SUDOERS_FILE"
    exit 1
fi

echo ""
echo -e "${GREEN}=== Installation Complete ===${NC}"
echo ""
echo "The deploy user '$DEPLOY_USER' can now run:"
echo "  sudo $PROJECT_DIR/scripts/setup_cron_backup.sh"
echo "  sudo $PROJECT_DIR/scripts/backup_postgres.sh"
echo ""
